//! The editor installation: a generated crate whose binary is olvin-editor
//! with the chosen elements linked in. Its `Cargo.toml` is the source of
//! truth for what is installed.

use std::path::{Path, PathBuf};
use std::process::{Child, Command};

use anyhow::{Context, Result, bail};
use toml_edit::{DocumentMut, Item, Value};

use crate::{Catalog, EngineSource};

pub struct EditorInstall {
    root: PathBuf,
}

impl EditorInstall {
    /// `<data dir>/olvin-hub/editor`, e.g. `~/.local/share/olvin-hub/editor`.
    pub fn locate() -> Result<Self> {
        let data = dirs::data_dir().context("this platform has no data directory")?;
        Ok(Self::at(data.join("olvin-hub/editor")))
    }

    pub fn at(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    pub fn root(&self) -> &Path {
        &self.root
    }

    pub fn binary(&self) -> PathBuf {
        let name = if cfg!(windows) {
            "olvin-editor.exe"
        } else {
            "olvin-editor"
        };
        self.root.join("target/release").join(name)
    }

    pub fn is_generated(&self) -> bool {
        self.root.join("Cargo.toml").is_file()
    }

    pub fn is_built(&self) -> bool {
        self.binary().is_file()
    }

    /// Ids of installed editor elements, in catalog order.
    pub fn installed(&self, catalog: &Catalog) -> Vec<String> {
        let Ok(text) = std::fs::read_to_string(self.root.join("Cargo.toml")) else {
            return Vec::new();
        };
        let Ok(doc) = text.parse::<DocumentMut>() else {
            return Vec::new();
        };
        let Some(deps) = doc.get("dependencies").and_then(Item::as_table_like) else {
            return Vec::new();
        };
        catalog
            .editor_modules
            .iter()
            .filter(|m| deps.contains_key(&m.package))
            .map(|m| m.id.clone())
            .collect()
    }

    /// What a fresh install gets: catalog defaults, or what's there already.
    pub fn initial_selection(&self, catalog: &Catalog) -> Vec<String> {
        if self.is_generated() {
            self.installed(catalog)
        } else {
            catalog
                .editor_modules
                .iter()
                .filter(|m| m.default)
                .map(|m| m.id.clone())
                .collect()
        }
    }

    /// (Re)generates the installation crate for exactly these elements.
    pub fn write(&self, engine: &EngineSource, catalog: &Catalog, ids: &[String]) -> Result<()> {
        engine.validate()?;
        if let EngineSource::Path(path) = engine
            && !path.join("editor/olvin_editor/Cargo.toml").is_file()
        {
            bail!(
                "{}: this Olvin version has no editor (editor/olvin_editor)",
                path.display()
            );
        }
        for id in ids {
            if catalog.editor_module(id).is_none() {
                bail!("no editor element `{id}`");
            }
        }
        // Catalog order keeps the generated files stable.
        let modules: Vec<_> = catalog
            .editor_modules
            .iter()
            .filter(|m| ids.contains(&m.id))
            .collect();

        let mut doc: DocumentMut = CARGO_TOML.parse()?;
        let deps = doc["dependencies"]
            .as_table_mut()
            .context("the editor template has no [dependencies] table")?;
        deps.insert(
            "olvin_editor",
            Item::Value(Value::InlineTable(
                engine.crate_dependency("editor/olvin_editor"),
            )),
        );
        for m in &modules {
            deps.insert(
                &m.package,
                Item::Value(Value::InlineTable(engine.crate_dependency(&m.path))),
            );
        }

        let plugins: String = modules
            .iter()
            .map(|m| format!("        Box::new({}),\n", m.plugin))
            .collect();
        let names: Vec<_> = modules.iter().map(|m| m.name.as_str()).collect();
        let main = format!(
            "// Generated by olvin-hub. Elements: {}.\n// Do not edit: `olvin-hub editor add/remove` overwrites this file.\n\nfn main() {{\n    olvin_editor::run(vec![\n{plugins}    ]);\n}}\n",
            if names.is_empty() {
                "core only".into()
            } else {
                names.join(", ")
            },
        );

        std::fs::create_dir_all(self.root.join("src"))?;
        std::fs::write(self.root.join("Cargo.toml"), doc.to_string())?;
        std::fs::write(self.root.join("src/main.rs"), main)?;
        Ok(())
    }

    /// `cargo build --release` of the installation. The caller decides how to run it.
    pub fn build_command(&self) -> Command {
        let mut cmd = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()));
        cmd.args(["build", "--release", "--manifest-path"])
            .arg(self.root.join("Cargo.toml"));
        cmd
    }

    /// Records which engine sources this build was made from.
    pub fn mark_built(&self, engine: &EngineSource) {
        if let Some(stamp) = engine_fingerprint(engine) {
            let _ = std::fs::write(self.root.join(STAMP), stamp.to_string());
        }
    }

    /// The engine changed since the editor was built (local engine checkouts
    /// only; git sources are pinned by Cargo.lock).
    pub fn is_stale(&self, engine: &EngineSource) -> bool {
        if !self.is_built() {
            return false;
        }
        let Some(current) = engine_fingerprint(engine) else {
            return false;
        };
        let built = std::fs::read_to_string(self.root.join(STAMP))
            .ok()
            .and_then(|s| s.trim().parse::<u64>().ok())
            .or_else(|| {
                std::fs::metadata(self.binary())
                    .ok()
                    .and_then(|m| mtime(&m))
            });
        built.is_none_or(|b| current > b)
    }

    pub fn launch(&self, project: Option<&Path>) -> Result<Child> {
        self.launch_with(project, false)
    }

    /// Starts the editor. `read_only`: the user chose not to trust the project
    /// (`OLVIN_TRUST_MODE=readonly`), so the editor does not ask again and
    /// refuses to run cargo or shell commands for it.
    pub fn launch_with(&self, project: Option<&Path>, read_only: bool) -> Result<Child> {
        if !self.is_built() {
            bail!("the editor is not built. Install it: olvin-hub editor install");
        }
        let mut cmd = Command::new(self.binary());
        if let Some(project) = project {
            cmd.arg(project);
        }
        if read_only {
            cmd.env(olvin_trust::MODE_ENV, "readonly");
        } else {
            cmd.env_remove(olvin_trust::MODE_ENV);
        }
        cmd.spawn().context("could not start olvin-editor")
    }
}

const STAMP: &str = ".engine-stamp";

/// Newest modification time (seconds) of the engine's sources: Rust, manifests, shaders.
pub fn engine_fingerprint(engine: &EngineSource) -> Option<u64> {
    let EngineSource::Path(root) = engine else {
        return None;
    };
    fn walk(dir: &Path, newest: &mut u64) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let Ok(meta) = entry.metadata() else { continue };
            if meta.is_dir() {
                if path
                    .file_name()
                    .is_some_and(|n| n != "target" && !n.to_string_lossy().starts_with('.'))
                {
                    walk(&path, newest);
                }
            } else if path
                .extension()
                .is_some_and(|e| e == "rs" || e == "toml" || e == "wgsl")
                && let Some(t) = mtime(&meta)
            {
                *newest = (*newest).max(t);
            }
        }
    }
    let mut newest = 0;
    for dir in ["crates", "editor"] {
        walk(&root.join(dir), &mut newest);
    }
    if let Some(t) = std::fs::metadata(root.join("Cargo.lock"))
        .ok()
        .and_then(|m| mtime(&m))
    {
        newest = newest.max(t);
    }
    (newest > 0).then_some(newest)
}

fn mtime(meta: &std::fs::Metadata) -> Option<u64> {
    meta.modified()
        .ok()?
        .duration_since(std::time::UNIX_EPOCH)
        .ok()
        .map(|d| d.as_secs())
}

const CARGO_TOML: &str = r#"# Generated by olvin-hub: the Olvin editor installation.
# Do not edit by hand: `olvin-hub editor add/remove` overwrites this file.

[package]
name = "olvin-editor-install"
version = "0.1.0"
edition = "2024"
publish = false

[[bin]]
name = "olvin-editor"
path = "src/main.rs"

[dependencies]

[profile.release]
lto = "thin"

# Standalone: never part of an enclosing workspace.
[workspace]
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_install_with_selected_elements() {
        let dir = std::env::temp_dir().join(format!("olvin-hub-editor-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let install = EditorInstall::at(&dir);
        let catalog = Catalog::builtin();
        let engine = EngineSource::default();

        assert_eq!(
            install.initial_selection(&catalog),
            ["console", "csg", "modeling", "uv", "library"]
        );
        install
            .write(&engine, &catalog, &["animator".into(), "console".into()])
            .unwrap();
        assert_eq!(install.installed(&catalog), ["console", "animator"]);
        let main = std::fs::read_to_string(dir.join("src/main.rs")).unwrap();
        assert!(main.find("ConsolePlugin").unwrap() < main.find("AnimatorPlugin").unwrap());

        install.write(&engine, &catalog, &[]).unwrap();
        assert!(install.installed(&catalog).is_empty());
        assert!(
            std::fs::read_to_string(dir.join("src/main.rs"))
                .unwrap()
                .contains("vec![\n    ]")
        );
        assert!(install.write(&engine, &catalog, &["nope".into()]).is_err());
        // Stale detection: no binary yet means "not built", not "stale".
        assert!(!install.is_stale(&engine));
        if let EngineSource::Path(_) = engine {
            assert!(engine_fingerprint(&engine).is_some());
        }
        std::fs::remove_dir_all(dir).unwrap();
    }
}
